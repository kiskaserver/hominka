// Шрифт інтерфейсу для ImGui.
//
// Вбудований у ImGui шрифт має лише латиницю — з ним будь-яка підказка
// українською перетворюється на суцільні «?». Тому беремо системний Segoe UI,
// той самий, яким набрано й сам чат, і ЯВНО просимо кирилицю: набір символів
// ImGui за замовчуванням її не містить, і про це легко забути — напис просто
// зникає, без жодної помилки.
//
// Окремі знаки, яких немає в жодному з наборів (хрестик, «мінус» у «A−»),
// дописуємо поіменно: інакше на їх місці порожні прямокутники.
#pragma once

struct ImFont;

namespace hominka {

// Кличеться після ImGui::CreateContext() і до першого кадру.
void load_ui_font(float size);

// Моноширинний, під код. Окремо, бо потрібен лише редакторові CSS: у чужому
// коді пропорційний шрифт зводить нанівець будь-яке вирівнювання.
// Повертає nullptr, якщо не завантажували, — тоді малюємо звичайним.
void load_mono_font(float size);
ImFont* mono_font();

}  // namespace hominka
