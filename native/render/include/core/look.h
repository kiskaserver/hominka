// Вигляд вікна й те, що людина з ним зробила.
//
// Окремим файлом, бо це спільне: рамку малюють два різні файли (ImGui під
// Windows, Blend2D під Linux), а от НАБІР значень і НАБІР подій мусить бути
// один. Інакше «покрутили прозорість» на одній системі означало б не те саме,
// що на іншій, і Python довелося б розбирати два випадки замість одного.
#pragma once

namespace hominka {

// Значення ті самі, що в config.json (opacity, bg_alpha, zoom), і назви
// навмисно ті самі.
struct Look {
    float opacity = 0.94f;      // прозорість усього вікна
    float bg_alpha = 0.30f;     // прозорість підкладки під чатом
    float zoom = 1.0f;          // кегль тексту
    bool frameless = false;     // «лише повідомлення»: без підкладки й рамки
    bool locked = false;        // клік-крізь: вікно не заважає ані грі, ані столу

    // Що лишається на екрані, коли вікно замкнене.
    //
    // Замок означає «не заважай мишею», а не «зникни», і далі думки
    // розходяться: одному потрібне зовсім чисте вікно поверх гри, другому —
    // смужка з числом глядачів перед очима весь ефір. Тому три окремі
    // вимикачі, а не один режим: кожен вмикає саме те, чого йому бракує.
    //
    // Значення за замовчуванням — те, як воно поводилося досі.
    bool lock_bg = true;        // підкладка й рамка під чатом
    bool lock_viewers = false;  // плашка з глядачами
    bool lock_header = false;   // смужка згори (кнопки видно, але миша крізь них проходить)
};

// Межі кегля — одні на всі кнопки «A−» і «A+».
//
// Тримати їх тут довелося не з любові до сталих: ті самі три кнопки живуть у
// трьох місцях (смужка вікна під Windows, така сама смужка під Linux, розділ
// «Вигляд» у налаштуваннях), і межі в них розійшлися. Під Windows «менше»
// впиралося в 50%, під Linux спускалося до 30% — те саме налаштування, той
// самий чат, різна поведінка.
//
// Нижня межа саме 30%: дрібніше вже не читається навіть у кадрі, а не тому,
// що щось зламається.
const float ZOOM_MIN = 0.3f;
const float ZOOM_MAX = 4.0f;
const float ZOOM_STEP = 0.1f;

inline float zoom_clamp(float z) {
    return z < ZOOM_MIN ? ZOOM_MIN : (z > ZOOM_MAX ? ZOOM_MAX : z);
}

// Що людина щойно зробила. Рендер збирає це за кадр і віддає Python, щоб той
// зберіг у config.json — правда про налаштування лишається в одному місці.
struct ChromeEvents {
    bool look_changed = false;      // покрутили повзунок або натиснули A+/A−
    bool lock_changed = false;
    bool geometry_changed = false;  // перетягнули або розтягнули
    bool open_settings = false;     // натиснули шестерню
    bool close = false;             // натиснули хрестик
};

}  // namespace hominka
