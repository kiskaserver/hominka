// Рамка вікна чату: підкладка, смужка перетягування, замок, шестерня,
// повзунки й куточок для розтягування.
//
// Це те саме, що робили hominka/ui/chrome.py і частина панелі налаштувань, —
// але вже в самому вікні оверлея. Причина проста: на етапі 2 вікно чату більше
// не Qt-вікно, а це, нативне. Отже, і крутити його має воно.
//
// Чому Dear ImGui. Малювати кнопки й повзунки «руками» на Direct2D означало б
// писати обробку наведення, натискання, захоплення миші й повторюваності — тобто
// цілий інтерфейсний рушій заради семи елементів керування. ImGui це вже вміє,
// важить кілька файлів і не тягне жодної залежності.
//
// Розподіл праці з Direct2D: підкладку й рамку малює D2D (там скруглення й
// прозорість того самого штибу, що й у чаті), а все, з чим взаємодіють мишею, —
// ImGui поверх. Обидва пишуть у той самий задній буфер, між ними — EndDraw.
#pragma once

#include <windows.h>
#include <d2d1_1.h>
#include <d3d11.h>

#include <string>

#include "core/look.h"

struct ImGuiContext;

namespace hominka {

// Look і ChromeEvents — спільні з Linux-рамкою (look.h): набір значень і
// набір подій мусить бути один, інакше Python розбирав би два випадки.

class Chrome {
public:
    bool init(HWND hwnd, ID3D11Device* dev, ID3D11DeviceContext* ctx);
    void shutdown();

    // Обробник повідомлень вікна — ставиться в DCompWindow::set_msg_hook.
    static LRESULT msg_hook(HWND h, UINT m, WPARAM w, LPARAM l, bool* handled);

    // Питає систему, де курсор. Кличеться ЩОКАДРУ, ще до рішення «малювати чи
    // ні»: без цього вікно, яке нічого не малює, ніколи б і не дізналося, що на
    // нього навели, — і рамка не з'явилася б.
    //
    // blocked — курсор зараз над НАШИМ іншим вікном (налаштування, редактор
    // теми). Воно лежить поверх, і рамку чату під ним показувати нема сенсу;
    // без цієї перевірки вона блимала щоразу, коли курсор ішов до налаштувань
    // краєм вікна чату.
    bool poll_hover(HWND hwnd, bool blocked = false);

    // Чи миша зараз над вікном. Поки її немає, рамку не показуємо взагалі:
    // поверх гри постійна смужка — це шум, а не зручність.
    bool hovered() const { return hovered_; }

    // Перші секунди після запуску рамку видно без наведення.
    //
    // Без цього щойно запущена програма — темний прямокутник, який нічим себе
    // не виказує: людина возить мишею по екрану, доки випадково не наведе. Це
    // не здогадка, це перше, що сказали про 3.0.1.
    void begin_intro(int ms);

    // Чи показувати рамку цього кадру. Одна відповідь на двох: і малювання, і
    // рішення «чи пускати мишу крізь вікно» мусять питати те саме.
    bool visible(bool locked) const;

    // Чи триває ще ті перші секунди. Замкнене вікно керування не показує, але
    // сказати «я тут, і я замкнене» мусить — інакше людина знову дивиться на
    // порожній екран і не знає, що програма запустилася.
    bool intro_active() const;

    // Підкладка й рамка — малює Direct2D, ДО чату.
    void draw_backdrop(ID2D1DeviceContext* d2d, int w, int h, const Look& look) const;

    // Елементи керування — малює ImGui, ПІСЛЯ чату.
    // Повертає, що людина зробила; look міняється на місці.
    //
    // viewers — готовий рядок про глядачів («60 866» або «T 60 866 · K 12 728»)
    // або порожньо. Складати його тут нема з чого: рамка не знає ані площадок,
    // ані налаштувань.
    // can_close — чи малювати хрестик. У режимі під Hominka на Python його
    // немає: там програму закриває вона, і другий хрестик означав би два різні
    // «закрити» з різними наслідками.
    // empty — у стрічці ще нічого; тоді замість порожнечі пишемо, що це за
    // вікно й куди натиснути.
    ChromeEvents draw_controls(int w, int h, Look* look, HWND hwnd,
                               const std::string& viewers, bool can_close, bool empty);

    // Чи ImGui зараз хоче мишу (курсор над кнопкою, тягнуть повзунок). Поки
    // хоче — вікно не можна робити клік-крізь, інакше натискання провалиться.
    bool wants_mouse() const;

private:
    bool ready_ = false;
    // Свій контекст ImGui. У процесі їх тепер троє (рамка чату, налаштування,
    // редактор теми), і кожен виклик ImGui треба робити саме у своєму: інакше
    // «згорни рамку» згортає чуже вікно, а те падає на найближчому кадрі.
    ImGuiContext* ctx_ = nullptr;
    bool hovered_ = false;
    unsigned long long intro_until_ = 0;   // доки показувати рамку без наведення
    // Курсор вийшов — рамка гасне не миттєво. Пройти по краю вікна дорогою до
    // іншого — звичайна річ, і блимання на кожен такий перетин дратує більше,
    // ніж зайва третина секунди зі смужкою на екрані.
    unsigned long long hover_until_ = 0;
    POINT mouse_ = {0, 0};        // курсор у координатах вікна
    // Перетягування за смужку: тримаємо, звідки взялися, щоб вікно не
    // «стрибало» під курсор при першому русі.
    bool dragging_ = false;
    POINT drag_anchor_ = {0, 0};
    RECT drag_origin_ = {0, 0, 0, 0};
    bool resizing_ = false;
    POINT resize_anchor_ = {0, 0};
    int resize_w_ = 0, resize_h_ = 0;
};

}  // namespace hominka
