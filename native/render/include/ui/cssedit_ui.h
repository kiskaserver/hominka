// Редактор «свій CSS» — сам вміст вікна, без вікна під ним.
//
// Головна відмінність від Qt-версії: тут немає окремого «попереднього
// перегляду». Він більше не потрібен — чат і редактор в одному процесі, тож
// правка лягає в САМУ стрічку, і людина бачить не схожу картинку, а точно те,
// що побачить глядач. Попередній перегляд був милицею, поки малював браузер.
//
// Праворуч — те, заради чого редактор і потрібен: список проблем (окремо
// помилки, окремо «рушій цього не вміє»), готові рецепти й довідник класів.
// Писати CSS для чужої розмітки без цього — гра у вгадайку.
#pragma once

#include <string>

namespace hominka {

struct CssEditState {
    std::string text;              // те, що зараз у полі
    int tab = 0;                   // 0 проблеми, 1 рецепти, 2 довідник
    int cursor_line = 1;
    int64_t typed_ms = 0;          // коли востаннє щось змінили
    bool pending = false;          // є незастосована правка
    bool samples_on = false;       // зразки зараз сиплються у стрічку
};

struct CssEditEvents {
    bool apply = false;            // текст змінився й час його застосувати
    bool close = false;
    bool samples = false;          // увімкнути або вимкнути зразки у стрічці
    bool title_active = false;     // тягнуть за заголовок
};

CssEditEvents draw_css_editor(CssEditState* st, int w, int h, int64_t now_ms);

}  // namespace hominka
