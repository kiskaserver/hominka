// Дрібні елементи, спільні для двох панелей.
//
// Панель налаштувань і редактор теми — різні вікна з різними завданнями, але
// кнопка «закрити» в них одна й та сама. Доки кожна малювала її сама, вони й
// розходилися: в одній хрестик стояв на дев'ять пікселів вище, ніж у другій, і
// жодна з двох не була вирівняна по заголовку.
#pragma once

// ImDrawList оголошуємо ПОЗА своїм простором імен: усередині це був би інший,
// власний тип із тією ж назвою — компілятор так і сказав.
struct ImDrawList;

namespace hominka {

// Напис у цілих пікселях.
//
// Гліфи растеризовані з хінтингом, тобто їхні лінії вже лягли рівно на пікселі.
// Поставити такий гліф на пів пікселя означає віддати його білінійній вибірці —
// і вся робота хінтера йде нанівець: краї розмиваються нерівно, і текст читається
// як «піксельний». Тому кожен наш власний напис округлюється; ImGui свої й так
// ставить у цілих.
void text_at(ImDrawList* dl, float x, float y, unsigned int color, const char* text);

// Кнопка без заливки — «другорядна дія». width = 0 означає «по тексту».
bool ghost(const char* label, float width = 0.0f);

// Хрестик заголовка: квадрат size x size у координатах вікна, з червоною
// підкладкою при наведенні. Хрестик — дві риски, а не символ «×»: гліф є не в
// кожному шрифті й у кожному свого розміру, а дві риски завжди однакові.
bool close_button(float x, float y, float size);

// Значок програми — той самий, що на ярлику. Малюємо, а не вантажимо картинку:
// на двох десятках пікселів від цього нічого не втрачається, зате не треба ані
// файлу поруч, ані текстури в атласі. x, y — лівий верхній кут, s — сторона.
void app_logo(ImDrawList* dl, float x, float y, float s);

}  // namespace hominka
