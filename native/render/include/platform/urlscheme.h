// Посилання hominka:// — «встановити тему з сайту одним клацанням».
//
// Як це влаштовано. На сайті кнопка веде на hominka://theme/<id>. Windows
// знаходить нас за записом у реєстрі й запускає з цим посиланням у аргументах.
// Якщо програма вже працює — новий процес не піднімає друге вікно, а передає
// посилання тому, що вже живе, і тихо виходить.
//
// Чому в посиланні лише ІМ'Я теми, а не сам CSS. Клацнути на таке посилання
// може будь-яка сторінка в інтернеті, і якби ми брали з нього код, то будь-хто
// міг би підсунути стрімеру довільний CSS у чат — від нечитабельного до такого,
// що тягне картинки з чужого сервера (а це вже його IP у чужому журналі). Тому
// з посилання ми беремо саме ім'я, а сам код теми качаємо з hominka.app по
// HTTPS. Найгірше, що може зробити чужа сторінка, — запропонувати одну з наших
// же тем. І навіть це — лише запропонувати: ставить її людина кнопкою.
#pragma once

#include <string>

namespace hominka {

// Записує в реєстр (HKCU — свого користувача, без прав адміністратора), що
// hominka:// відкриваємо ми. Кличеться на кожному старті: шлях до програми
// змінюється після оновлення, та й запис можуть затерти.
void register_url_scheme();

// Ім'я теми з посилання: «hominka://theme/anime» → «anime». Порожньо — це не
// наше посилання або ім'я підозріле. Приймаємо лише малі літери, цифри й
// дефіс: ім'я йде в адресу запиту, і пускати туди будь-що не можна.
std::string theme_id_from_url(const std::string& url);

// Передає посилання вже запущеній копії. true — передали, нам лишається тихо
// вийти. false — нікого немає, працюємо самі.
bool forward_to_running(const std::string& url);

// Посилання, яке треба обробити. Кладуть його двоє: обробник WM_COPYDATA (нам
// передала інша копія) і сам запуск, якщо програму підняли цим посиланням.
void deliver_url(const std::string& url);

// Порожньо — нічого не приходило. Читання забирає значення: подія одноразова.
std::string take_delivered_url();

// Обробник WM_COPYDATA. Ставиться в ланцюжок повідомлень вікна чату.
bool handle_copydata(unsigned msg, void* lparam);

}  // namespace hominka
