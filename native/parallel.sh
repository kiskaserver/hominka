#!/bin/sh
# Спільна частина обох збірок: компілювати по файлу на ядро, а не стовпчиком.
#
# Навіщо взагалі: рендер чату - це сорок файлів, і доки вони йшли ОДНИМ
# викликом g++, шість ядер робили роботу одного. Збірка тривала 384 секунди,
# з них 349 - саме тут (і ще раз стільки ж на відладочну копію).
#
# Підключається через «. "$SRC/parallel.sh"» на початку build.sh і
# build_linux.sh. Очікує, що SRC уже виставлено.

# Скільки компіляцій тримати одночасно.
JOBS="${JOBS:-$(nproc 2>/dev/null || echo 4)}"

# Запустити у фоні й запам'ятати. Просто «&» тут мало: з set -e падіння
# фонового завдання лишилося б непоміченим, і збірка «успішно» виклала б
# половину файлів.
BG_PIDS=""
bg() { "$@" & BG_PIDS="$BG_PIDS $!"; }
bg_wait() {
    st=0
    for p in $BG_PIDS; do wait "$p" || st=1; done
    BG_PIDS=""
    [ "$st" -eq 0 ] || { echo "!! паралельна збірка впала - див. вище"; exit 1; }
}

# Один файл - один .o. Окремим скриптом, бо функцію в xargs не передати, а
# плодити цитування в один рядок - швидкий спосіб зробити помилку, якої
# потім не видно.
cat > /tmp/cc1.sh <<'ONE'
#!/bin/sh
set -e
src="$1"
out="$OBJDIR/$(echo "$src" | tr '/' '_').o"
# TU_CXX і TU_FLAGS навмисно без лапок: це кілька слів кожне.
exec $TU_CXX $TU_FLAGS -c "$src" -o "$out"
ONE
chmod +x /tmp/cc1.sh

# Скомпілювати список файлів паралельно й злінкувати:
#   $1 компілятор, $2 тека для .o, $3 прапорці компіляції,
#   $4 куди лінкувати, $5 прапорці лінкування, $6 бібліотеки, далі - файли.
build_parallel() {
    TU_CXX="$1"; OBJDIR="$2"; TU_FLAGS="$3"
    link_out="$4"; link_flags="$5"; link_libs="$6"
    shift 6
    export TU_CXX OBJDIR TU_FLAGS
    rm -rf "$OBJDIR"
    mkdir -p "$OBJDIR"
    printf '%s\n' "$@" | xargs -P "$JOBS" -n 1 /tmp/cc1.sh
    $TU_CXX $link_flags -o "$link_out" "$OBJDIR"/*.o $link_libs
}
