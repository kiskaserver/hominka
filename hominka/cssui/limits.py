"""Чого нативний рушій не вміє — і що робити натомість.

Один список на всю програму: за ним і попереджає редактор, і пишеться довідник.
Тримати їх окремо означало б, що одного дня вони розійдуться, і людина
прочитає в довіднику одне, а в підказці — інше.

Звідки список. Чат малює litehtml (native/render), а не браузер. Він свідомо
менший: у ньому немає ані анімацій, ані фільтрів, ані сітки. Незрозуміле
правило він мовчки викидає — верстка від цього не ламається, але й не діє. Тому
головне не «попередити про все», а сказати, ЧИМ це замінити.

Перелік складено за тим, що рушій справді розбирає (список case у style.cpp
версії v0.10), а не за здогадами: помилкова підказка гірша за жодну.

Список меншає. Те, що трапляється в чужих темах найчастіше, ми доробляємо, а не
лишаємо в цьому файлі. Уже вміємо: opacity, box-shadow, transform і
vertical-align із довжиною (латки в native/patches/), filter: drop-shadow
(перекладаємо в text-shadow), «.m { animation: none }» (вимикає появу рядка),
«#list { flex-direction: column-reverse }» (новіші рядки згори). Довгі
посилання переносяться, як у браузері.
"""

# (властивість, коротко «що буде», чим замінити)
#
# Порядок має значення лише для довідника — там він читається згори вниз.
UNSUPPORTED = [
    ("filter",
     "не діє (крім filter: drop-shadow — його перекладаємо в text-shadow)",
     "тінь тексту — text-shadow, тінь рядка — box-shadow; решту ефектів "
     "доведеться закласти в самі кольори"),
    ("backdrop-filter",
     "не діє: матового скла не буде",
     "звичайна напівпрозорість: background: rgba(0,0,0,.45)"),
    ("animation",
     "не діє: рядок одразу в кінцевому стані",
     "поява рядка вже анімована самою програмою (зсув і проявлення); вимкнути "
     "її можна звичним «.m { animation: none }» — це програма розуміє"),
    ("transition",
     "не діє: змінюватися в оверлеї нема чому",
     "—"),
    ("mask",
     "не діє: елемент намалюється повністю",
     "—"),
    ("clip-path",
     "не діє: обрізання не буде",
     "скруглення кутів робить border-radius"),
    ("grid",
     "не діє: сітки немає",
     "рядок і так один; для розкладки всередині нього є flex"),
    ("letter-spacing",
     "не діє: відстань між літерами лишиться звичайною",
     "виділити нік чи назву можна жирністю (font-weight), кеглем або кольором"),
    ("word-break",
     "не діє",
     "довгі слова переносяться самі по пробілах"),
    ("text-overflow",
     "не діє: «…» замість обрізаного не буде",
     "—"),
]

# Швидкий доступ за іменем властивості.
BY_NAME = {name: (what, instead) for name, what, instead in UNSUPPORTED}

# Правила @, які рушій не виконує.
UNSUPPORTED_AT = {
    "keyframes": ("не діє: кадрів анімації рушій не програє",
                  "поява рядка вже анімована самою програмою"),
    "media": ("не діє: розмір вікна чату задає сама програма", "—"),
    "supports": ("не діє", "—"),
    "import": ("не діє: сторінка чату навмисно самодостатня й у мережу не ходить",
               "вставте потрібні правила прямо сюди"),
}


def note(prop: str):
    """Коротка підказка для властивості або None, якщо з нею все гаразд."""
    p = (prop or "").strip().lower()
    # Префікси постачальників («-webkit-mask») ведуть себе так само.
    for pref in ("-webkit-", "-moz-", "-ms-", "-o-"):
        if p.startswith(pref):
            p = p[len(pref):]
            break
    hit = BY_NAME.get(p)
    if hit:
        return hit
    # Складені імена: grid-template-columns, animation-name, mask-image…
    for name, (what, instead) in BY_NAME.items():
        if p.startswith(name + "-"):
            return (what, instead)
    return None
