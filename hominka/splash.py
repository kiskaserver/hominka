"""Заставка збірки одним файлом: рядок прогресу і зняття."""

def splash_text(text: str, percent: int = -1):
    """Рядок під смугою на заставці (і, за потреби, сама смуга).

    Поки триває розпаковування, туди пише сам bootloader; далі — ми, бо він
    уже віддав керування, а до появи вікна ще секунда-дві на запуск Qt.

    percent — прямий наказ смузі: «стань на стільки відсотків». Передається
    префіксом «NN|», який розбирає Tcl-скрипт заставки (див. Hominka_one.spec).
    Без цього смуга спинялася б там, де закінчив bootloader, і останні секунди
    запуску виглядали б як зависання.
    """
    try:
        import pyi_splash          # існує лише всередині збірки зі splash
        pyi_splash.update_text("%d|%s" % (percent, text) if percent >= 0 else text)
    except Exception:
        pass


def close_splash():
    """Прибирає заставку, щойно з'явилося справжнє вікно.

    Збірка одним файлом розпаковує себе при кожному запуску, і до появи вікна
    минає кілька секунд. Заставка — єдине, що в цей час каже «програма
    запускається», але зняти її мусимо ми: сама вона висітиме поверх усього.
    """
    try:
        import pyi_splash
        pyi_splash.close()
    except Exception:
        pass
